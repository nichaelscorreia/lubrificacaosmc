-- 1. TABELA DE USUÁRIOS DO SISTEMA
CREATE TABLE LUB_USUARIOS (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME VARCHAR2(120) NOT NULL,
    LOGIN VARCHAR2(50) NOT NULL UNIQUE,
    SENHA_HASH VARCHAR2(100) NOT NULL,
    PERFIL VARCHAR2(20) DEFAULT 'OPERADOR' NOT NULL CHECK (PERFIL IN ('ADMIN', 'GERENTE', 'OPERADOR', 'LEITURA')),
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL CHECK (ATIVO IN ('S', 'N')),
    ULTIMO_ACESSO DATE,
    DATA_CRIACAO DATE DEFAULT SYSDATE NOT NULL
);

-- 2. CATEGORIAS DE PRODUTOS E LUBRIFICANTES
CREATE TABLE LUB_CATEGORIAS_PRODUTO (
    ID_CATEGORIA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME_CATEGORIA VARCHAR2(80) NOT NULL UNIQUE,
    DESCRICAO VARCHAR2(255),
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL CHECK (ATIVO IN ('S', 'N'))
);

-- 3. CADASTRO DE PRODUTOS E LUBRIFICANTES
CREATE TABLE LUB_PRODUTOS (
    ID_PRODUTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_CATEGORIA NUMBER REFERENCES LUB_CATEGORIAS_PRODUTO(ID_CATEGORIA),
    CODIGO_PRODUTO VARCHAR2(30) UNIQUE,
    NOME_PRODUTO VARCHAR2(120) NOT NULL,
    VISCOSIDADE VARCHAR2(30), -- Ex: 15W40, 5W30, 80W90
    ESPECIFICACAO VARCHAR2(80), -- Ex: API CI-4, ACEA E7, DOT 4
    MARCA VARCHAR2(60),
    UNIDADE_MEDIDA VARCHAR2(10) DEFAULT 'L' NOT NULL, -- L, ML, UN, KG
    ESTOQUE_ATUAL NUMBER(12, 2) DEFAULT 0 NOT NULL,
    ESTOQUE_MINIMO NUMBER(12, 2) DEFAULT 0 NOT NULL,
    VALOR_UNITARIO NUMBER(12, 2) DEFAULT 0,
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL CHECK (ATIVO IN ('S', 'N')),
    DATA_CADASTRO DATE DEFAULT SYSDATE NOT NULL
);

-- 4. CONFIGURAÇÕES ADICIONAIS POR VEÍCULO
CREATE TABLE LUB_VEICULOS_CONFIG (
    CODIGO_VEICULO VARCHAR2(20) PRIMARY KEY,
    TIPO_CONTROLE VARCHAR2(10) DEFAULT 'KM' NOT NULL CHECK (TIPO_CONTROLE IN ('KM', 'HORAS', 'AMBOS')),
    INTERVALO_KM NUMBER(10) DEFAULT 10000,
    INTERVALO_HORAS NUMBER(10) DEFAULT 250,
    INTERVALO_MESES NUMBER(4) DEFAULT 6,
    CAPACIDADE_CARTER_LITROS NUMBER(8, 2),
    VISCOSIDADE_RECOMENDADA VARCHAR2(30),
    FILTRO_OLEO_REF VARCHAR2(50),
    FILTRO_AR_REF VARCHAR2(50),
    FILTRO_COMBUSTIVEL_REF VARCHAR2(50),
    ULTIMA_TROCA_ID NUMBER,
    STATUS_TROCA VARCHAR2(20) DEFAULT 'SEM_REGISTRO' CHECK (STATUS_TROCA IN ('REGULAR', 'ALERTA', 'VENCIDO', 'SEM_REGISTRO')),
    DATA_ATUALIZACAO DATE DEFAULT SYSDATE
);

-- 5. REGISTROS DE ORDENS DE SERVIÇO / TROCAS DE ÓLEO
CREATE TABLE LUB_REGISTROS_TROCA (
    ID_TROCA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NUMERO_OS VARCHAR2(30) NOT NULL UNIQUE,
    CODIGO_VEICULO VARCHAR2(20) NOT NULL,
    DATA_SERVICO DATE DEFAULT SYSDATE NOT NULL,
    KM_REGISTRADO NUMBER(10),
    HORAS_REGISTRADO NUMBER(10),
    TIPO_SERVICO VARCHAR2(30) DEFAULT 'TROCA_COMPLETA',
    LOCAL_EXECUCAO VARCHAR2(100),
    MECANICO_RESPONSAVEL VARCHAR2(100),
    TROCOU_OLEO_MOTOR CHAR(1) DEFAULT 'S',
    TROCOU_FILTRO_OLEO CHAR(1) DEFAULT 'S',
    TROCOU_FILTRO_AR CHAR(1) DEFAULT 'N',
    TROCOU_FILTRO_COMBUSTIVEL CHAR(1) DEFAULT 'N',
    TROCOU_FILTRO_CABINE CHAR(1) DEFAULT 'N',
    LUBRIFICOU_CHASSIS CHAR(1) DEFAULT 'N',
    TROCOU_OLEO_CAMBIO CHAR(1) DEFAULT 'N',
    TROCOU_OLEO_DIFERENCIAL CHAR(1) DEFAULT 'N',
    TROCOU_FLUIDO_FREIO CHAR(1) DEFAULT 'N',
    TROCOU_ARREFECIMENTO CHAR(1) DEFAULT 'N',
    KM_PROXIMA_TROCA NUMBER(10),
    DATA_PROXIMA_TROCA DATE,
    HORAS_PROXIMA_TROCA NUMBER(10),
    VALOR_TOTAL_SERVICO NUMBER(12, 2) DEFAULT 0,
    CHECKLIST_STATUS VARCHAR2(20) DEFAULT 'OK',
    OBSERVACOES VARCHAR2(1000),
    ID_USUARIO_REGISTRO NUMBER REFERENCES LUB_USUARIOS(ID_USUARIO),
    DATA_CRIACAO DATE DEFAULT SYSDATE NOT NULL
);

-- 6. ITENS UTILIZADOS NA TROCA
CREATE TABLE LUB_ITENS_TROCA (
    ID_ITEM NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_TROCA NUMBER NOT NULL REFERENCES LUB_REGISTROS_TROCA(ID_TROCA) ON DELETE CASCADE,
    ID_PRODUTO NUMBER REFERENCES LUB_PRODUTOS(ID_PRODUTO),
    DESCRICAO_ITEM VARCHAR2(120) NOT NULL,
    QUANTIDADE NUMBER(10, 2) NOT NULL,
    UNIDADE_MEDIDA VARCHAR2(10) DEFAULT 'L',
    VALOR_UNITARIO NUMBER(12, 2) DEFAULT 0,
    VALOR_TOTAL NUMBER(12, 2) DEFAULT 0
);

-- 7. MOVIMENTAÇÕES DE ESTOQUE
CREATE TABLE LUB_MOVIMENTACOES_ESTOQUE (
    ID_MOVIMENTO NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_PRODUTO NUMBER NOT NULL REFERENCES LUB_PRODUTOS(ID_PRODUTO),
    TIPO_MOVIMENTO VARCHAR2(10) NOT NULL CHECK (TIPO_MOVIMENTO IN ('ENTRADA', 'SAIDA', 'AJUSTE')),
    QUANTIDADE NUMBER(12, 2) NOT NULL,
    SALDO_ANTERIOR NUMBER(12, 2) NOT NULL,
    SALDO_POSTERIOR NUMBER(12, 2) NOT NULL,
    VALOR_UNITARIO NUMBER(12, 2) DEFAULT 0,
    MOTIVO VARCHAR2(255),
    NUMERO_NF VARCHAR2(50),
    FORNECEDOR VARCHAR2(120),
    ID_TROCA NUMBER REFERENCES LUB_REGISTROS_TROCA(ID_TROCA),
    ID_USUARIO NUMBER REFERENCES LUB_USUARIOS(ID_USUARIO),
    DATA_MOVIMENTO DATE DEFAULT SYSDATE NOT NULL
);

-- 8. AUDITORIA DE OPERAÇÕES DO SISTEMA
CREATE TABLE LUB_AUDITORIA (
    ID_AUDITORIA NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ID_USUARIO NUMBER,
    LOGIN_USUARIO VARCHAR2(50),
    ACAO VARCHAR2(50) NOT NULL,
    TABELA VARCHAR2(50),
    ID_REGISTRO VARCHAR2(50),
    DETALHES VARCHAR2(2000),
    IP_ORIGEM VARCHAR2(50),
    DATA_HORA DATE DEFAULT SYSDATE NOT NULL
);

-- ÍNDICES DE PERFORMANCE
CREATE INDEX IDX_LUB_REG_VEIC ON LUB_REGISTROS_TROCA(CODIGO_VEICULO);
CREATE INDEX IDX_LUB_REG_DATA ON LUB_REGISTROS_TROCA(DATA_SERVICO);
CREATE INDEX IDX_LUB_ITENS_TROCA ON LUB_ITENS_TROCA(ID_TROCA);
CREATE INDEX IDX_LUB_MOV_PROD ON LUB_MOVIMENTACOES_ESTOQUE(ID_PRODUTO);
CREATE INDEX IDX_LUB_AUDIT_DATA ON LUB_AUDITORIA(DATA_HORA);
